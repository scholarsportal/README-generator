import { NextRequest, NextResponse } from 'next/server'

const SITE = 'https://borealisdata.ca'

export async function POST(req: NextRequest) {
  try {
    const { pid, token, markdown } = await req.json()

    if (!pid || !token || !markdown) {
      return NextResponse.json({ message: 'Missing pid, token, or markdown' }, { status: 400 })
    }

    const blob = Buffer.from(markdown, 'utf-8')
    const boundary = `----FormBoundary${Math.random().toString(16).slice(2)}`

    // Build multipart/form-data manually (Node fetch FormData support varies)
    const metaPart = JSON.stringify({
      description: 'README generated by borealis-readme-gen',
      categories: ['Documentation'],
      restrict: false,
    })

    const body = [
      `--${boundary}`,
      `Content-Disposition: form-data; name="jsonData"`,
      '',
      metaPart,
      `--${boundary}`,
      `Content-Disposition: form-data; name="file"; filename="README.md"`,
      `Content-Type: text/markdown`,
      '',
      markdown,
      `--${boundary}--`,
    ].join('\r\n')

    const res = await fetch(
      `${SITE}/api/v1/datasets/:persistentId/add?persistentId=${encodeURIComponent(pid)}`,
      {
        method: 'POST',
        headers: {
          'X-Dataverse-key': token,
          'Content-Type': `multipart/form-data; boundary=${boundary}`,
          'Content-Length': Buffer.byteLength(body).toString(),
        },
        body,
      }
    )

    if (!res.ok) {
      const err = await res.json().catch(() => ({}))
      return NextResponse.json(
        { message: (err as { message?: string }).message || `Borealis returned ${res.status}` },
        { status: res.status }
      )
    }

    return NextResponse.json({ ok: true })
  } catch (e) {
    return NextResponse.json({ message: String(e) }, { status: 500 })
  }
}
